from decimal import Decimal

LANGS = ("ru", "ky")
DEFAULT = "ru"
_current = contextvars.ContextVar("depter_lang", default=DEFAULT)


def set_lang(code):
    _current.set(code if code in LANGS else DEFAULT)


def get_lang():
    return _current.get()


def tr(key, **kw):
    pair = T.get(key)
    if pair is None:
        return key
    text = pair[0] if get_lang() == "ru" else pair[1]
    return text.format(**kw) if kw else text


def whole(value):
    return int(Decimal(value).quantize(Decimal(1)))


def fmt_money(value):
    value = Decimal(value)
    s = f"{int(value):,}" if value == value.to_integral_value() else f"{value:,.2f}"
    return s.replace(",", "\u00a0")


